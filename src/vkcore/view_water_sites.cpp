std::string hex(const std::uint8_t* bytes, std::size_t count) {
    std::string out;
    char cell[4];
    for (std::size_t i = 0; i < count; ++i) {
        std::snprintf(cell, sizeof(cell), i == 0 ? "%02X" : " %02X", bytes[i]);
        out += cell;
    }
    return out;
}

