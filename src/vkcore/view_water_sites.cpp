bool known(const std::byte* base) {
    bool all = true;
    for (const Bytes& b : kChecks) {
        if (std::memcmp(base + b.rva, b.bytes, b.count) != 0) {
            EVR_LOG("%s: RVA 0x%X is not as known: %s, expected %s", kTag, b.rva,
                    hex(reinterpret_cast<const std::uint8_t*>(base + b.rva), b.count).c_str(),
                    hex(b.bytes, b.count).c_str());
            all = false;
        }
    }
    return all;
}

const std::byte* ripTarget(const std::byte* base, std::uint32_t rva) {
    std::int32_t disp = 0;
    std::memcpy(&disp, base + rva + 3, sizeof(disp));
    return base + rva + 7 + disp;
}

