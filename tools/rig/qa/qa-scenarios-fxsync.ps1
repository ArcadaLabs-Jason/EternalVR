# The particle sync on by default (T-230, docs/rig-findings/stereo-fx-lag.md): CPU particles and effects alike in both
# eyes. Dot-sourced by qa-suite.ps1 after qa-scenarios-unseen.ps1: added to $script:QaScenarios before the launcher's
# end-to-end suite.
#
#   fx-sync  e1m3 outdoors (the snow and ice of the 0.1.34 tiles), nothing set: the sync's start-up lines (the four
#            hooks, the GPU particle stages bound by eye R, the ray-traced particle mask kept), and from its 10 s lines
#            in play: eye R reused eye L's ring in every window, never advanced it, and handled every particle system
#            with GPU particles it met (U equal to W, W above 0: the tiles' case on screen), eye R's GPU particle
#            emitter records at least half of eye L's, the ray-traced particle mask kept; no `Bump
#            MAX_TRANSPARENCY_QUADS` in the game's console log. Positive control: the same checks on a run with
#            ETERNALVR_STEREO_FX_SYNC_GPU=0 (0.1.34's reuse of the GPU-staged systems, which drew the tiles) fail U
#            equal to W and the emitter records.

$script:QaFxMap = 'game/sp/e1m3_cult/e1m3_cult -checkpoint cp_03_shoot_gate'
# The outdoor starts of fxg-tour3.sh (2026-10-08): the tiles were at game_player_start_5 in a player's capture.
$script:QaFxSchedule = '3:god;notarget;g_setting_hud_auto_dismiss_tutorials 1;g_setting_tutorials 0|8:teleport game_player_start_5|30:teleport game_player_start_3|52:teleport game_player_start_8'
$script:QaFxLine = "seq-fx: eye R reused eye L's particles (\d+) time\(s\) \((\d+) particle system\(s\), (\d+) effect\(s\)\), light pool kept (\d+); eye R generated (\d+) / (\d+) itself \(eye L had not\) and (\d+) GPU-staged particle system\(s\) eye L had \((\d+) GPU stage\(s\) bound\); eye L's particle systems with GPU particles (\d+); generated by eye L (\d+) / (\d+), eye R (\d+) / (\d+) \(particle systems / effects\); ring advances eye L (\d+), eye R (\d+)(.*)$"
$script:QaFxGpu = 'eye L ([\d.]+) / ([\d.]+) / ([\d.]+), eye R ([\d.]+) / ([\d.]+) / ([\d.]+) \((\d+) / (\d+) GPU steps\)'
$script:QaFxMask = 'ray-traced particle mask kept by eye R (\d+), cleared eye L (\d+) / eye R (\d+)'
$script:QaFxMinWindows = 4

# The 10 s lines with eye R reuses (in play, stereo): their counters, the GPU readout and the mask's counts.
function Get-QaFxWindows($Ctx) {
    $out = New-Object System.Collections.ArrayList
    foreach ($line in (Get-QaMatches $Ctx $script:QaFxLine -Regex)) {
        if ($line -notmatch $script:QaFxLine) { continue }
        $n = @(1..15 | ForEach-Object { [long]$Matches[$_] })
        $tail = $Matches[16]
        if ($n[0] -eq 0) { continue }
        $w = [pscustomobject]@{ Reused = $n[0]; PoolKept = $n[3]; GpuOwn = $n[6]; GpuMet = $n[8]; AdvR = $n[14]
                                RecL = $null; RecR = $null; MaskKept = $null }
        if ($tail -match $script:QaFxGpu) { $w.RecL = [double]$Matches[1]; $w.RecR = [double]$Matches[4] }
        if ($tail -match $script:QaFxMask) { $w.MaskKept = [long]$Matches[1] }
        [void]$out.Add($w)
    }
    return $out
}

# The game's console log of this run (written by the game in its user folder), or '' when the run did not write it.
function Get-QaGameConsole($Ctx) {
    $path = Join-Path $env:USERPROFILE 'Saved Games\id Software\DOOMEternal\base\qconsole.log'
    if (-not (Test-Path -LiteralPath $path) -or (Get-Item -LiteralPath $path).LastWriteTime -lt $Ctx.Since) { return '' }
    return Read-QaShared $path
}

$fxSyncScenarios = @(
    @{
        Name = 'fx-sync'; Kind = 'game'
        Map = $script:QaFxMap
        Proves = "CPU particles and effects alike in both eyes by default: the particle sync's hooks in, eye R reusing eye L's ring with every GPU-staged particle system handled (the 0.1.34 tiles' case) and the ray-traced particle mask kept, outdoors in e1m3"
        Env = @("ETERNALVR_DEBUG_COMMANDS=$script:QaFxSchedule")
        Input = $script:QaRestPose
        Timeline = {
            param($c)
            Wait-QaSeconds $c 20; Save-QaXrShot $c 'snow'
            Wait-QaSeconds $c 50; Save-QaShot $c 'end'
        }
        Asserts = {
            param($c)
            Test-QaPresent $c "seq-fx: ring advance \(RVA 0x[0-9A-F]+\), light pool reset \(0x[0-9A-F]+\), particle \(0x[0-9A-F]+\) and effect \(0x[0-9A-F]+, exit 0x[0-9A-F]+\) generation hooked: eye R draws eye L's particles and effects" -Regex
            Test-QaPresent $c 'seq-fx: GPU particle stages bound by eye R'
            Test-QaPresent $c "seq-fx: ray-traced particle mask: eye R keeps eye L's"
            Test-QaAbsent $c 'seq-fx: [^\r\n]*(did not check out|failed)' -Regex
            $w = @(Get-QaFxWindows $c)
            Add-QaResult $c "eye R reused eye L's particles in $($script:QaFxMinWindows) or more 10 s windows" ($w.Count -ge $script:QaFxMinWindows) "$($w.Count) window(s)"
            if ($w.Count -eq 0) { return }
            $adv = @($w | Where-Object { $_.AdvR -ne 0 })
            Add-QaResult $c 'eye R never advanced the ring' ($adv.Count -eq 0) "$($adv.Count) window(s) with eye R advances"
            # The two counts are taken a few instructions apart, so a 10 s line can split one prepare between them.
            $pool = @($w | Where-Object { [Math]::Abs($_.PoolKept - $_.Reused) -gt 2 })
            Add-QaResult $c "eye R kept eye L's light pool with its ring" ($pool.Count -eq 0) "$($pool.Count) window(s) differ by more than 2"
            $met = ($w | Measure-Object GpuMet -Sum).Sum
            $own = ($w | Measure-Object GpuOwn -Sum).Sum
            Add-QaResult $c 'GPU-staged particle systems on screen and every one handled by eye R (U = W)' ($met -gt 0 -and $own -eq $met) "W $met, U $own"
            $rec = @($w | Where-Object { $null -ne $_.RecL -and $_.RecL -gt 0 })
            $low = @($rec | Where-Object { $_.RecR -lt 0.5 * $_.RecL })
            Add-QaResult $c "eye R's GPU particle emitter records at least half of eye L's" ($rec.Count -gt 0 -and $low.Count -eq 0) `
                "$($rec.Count) window(s) with eye L records, $($low.Count) below half"
            $mask = ($w | Where-Object { $null -ne $_.MaskKept } | Measure-Object MaskKept -Sum).Sum
            Add-QaResult $c "eye R kept eye L's ray-traced particle mask" ($mask -gt 0) "kept $mask"
            $console = Get-QaGameConsole $c
            if ($console) {
                $bump = @($console -split "`r?`n" | Where-Object { $_ -match 'MAX_TRANSPARENCY_QUADS' })
                Add-QaResult $c 'absent from the game console: Bump MAX_TRANSPARENCY_QUADS' ($bump.Count -eq 0) "$($bump.Count) line(s)"
            } else {
                Add-QaNote $c 'the game console log was not written during the run: MAX_TRANSPARENCY_QUADS not checked'
            }
        }
    }
)

# Before the launcher's end-to-end suite, which stays last.
$e2e = @($script:QaScenarios | Where-Object { $_.Kind -eq 'e2e' })
$script:QaScenarios = @($script:QaScenarios | Where-Object { $_.Kind -ne 'e2e' }) + $fxSyncScenarios + $e2e
